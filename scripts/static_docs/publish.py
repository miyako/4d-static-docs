#!/usr/bin/env python3
"""Publish verified static-docs assets without overwriting an existing release."""

import argparse
import hashlib
import json
import re
import subprocess
import sys
import tempfile
from datetime import datetime, timezone
from pathlib import Path


def checked(command, **kwargs):
    return subprocess.run(command, check=True, text=True, **kwargs)


def validate_assets(assets):
    sums = assets / "SHA256SUMS"
    expected = {}
    for line in sums.read_text(encoding="ascii").splitlines():
        digest, name = line.split("  ", 1)
        if not re.fullmatch(r"[0-9a-f]{64}", digest) or Path(name).name != name:
            raise ValueError(f"Invalid checksum entry: {line}")
        path = assets / name
        with path.open("rb") as stream:
            actual = hashlib.file_digest(stream, "sha256").hexdigest()
        if actual != digest:
            raise ValueError(f"Asset checksum mismatch: {name}")
        expected[name] = digest
    required = {"docs.zip", "snapshot.json", "link-report.json"}
    if not required <= expected.keys():
        raise ValueError(f"Required assets absent from checksums: {required - expected.keys()}")
    snapshot = json.loads((assets / "snapshot.json").read_text(encoding="utf-8"))
    if snapshot["syntaxCapture"] and snapshot["syntaxCapture"]["asset"] not in expected:
        raise ValueError("Syntax capture is absent from checksums")
    return snapshot, sorted([*expected, "SHA256SUMS"])


def publish(args):
    assets = args.assets.resolve()
    snapshot, names = validate_assets(assets)
    tag = args.tag or (
        "static-docs-" + snapshot["sourceCommit"][:12] + "-"
        + datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    )
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._-]*", tag):
        raise ValueError("Release tag must contain only letters, digits, dots, underscores and hyphens")
    existing = subprocess.run(
        ["gh", "api", f"repos/{args.repository}/releases/tags/{tag}"],
        text=True, capture_output=True,
    )
    if existing.returncode == 0:
        release = json.loads(existing.stdout)
        if release["draft"] or {a["name"] for a in release["assets"]} != set(names):
            raise ValueError(f"Existing release has incomplete or different assets: {tag}")
        with tempfile.TemporaryDirectory(prefix="static-docs-release-") as directory:
            checked(["gh", "release", "download", tag, "--repo", args.repository, "--dir", directory])
            for name in names:
                with (assets / name).open("rb") as local, (Path(directory) / name).open("rb") as remote:
                    if hashlib.file_digest(local, "sha256").digest() != hashlib.file_digest(remote, "sha256").digest():
                        raise ValueError(f"Refusing to overwrite existing release asset: {tag}/{name}")
        print(release["html_url"])
        return
    if "HTTP 404" not in existing.stderr:
        raise RuntimeError(existing.stderr.strip() or "Unable to inspect existing release")
    notes = (
        f"Offline documentation snapshot from `{snapshot['sourceRepository']}` "
        f"at `{snapshot['sourceCommit']}`.\n\n"
        f"{snapshot['htmlPages']:,} HTML pages. Extract `docs.zip` to obtain `docs/` "
        "and `snapshot.json`; verify downloads against `SHA256SUMS`.\n\n"
        "Missing upstream targets remain public links and are listed in `link-report.json`. "
        "No assembled language data or embeddings are regenerated by this release.\n"
    )
    with tempfile.TemporaryDirectory(prefix="static-docs-notes-") as directory:
        notes_path = Path(directory) / "notes.md"
        notes_path.write_text(notes, encoding="utf-8")
        command = ["gh", "release", "create", tag, "--repo", args.repository,
                   "--target", args.target, "--title", args.title or tag,
                   "--notes-file", str(notes_path)]
        if args.prerelease:
            command.append("--prerelease")
        command.extend(str(assets / name) for name in names)
        checked(command)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--assets", required=True, type=Path)
    parser.add_argument("--repository", required=True)
    parser.add_argument("--target", required=True, help="Generator commit in the destination repository")
    parser.add_argument("--tag")
    parser.add_argument("--title")
    parser.add_argument("--prerelease", action="store_true")
    args = parser.parse_args()
    if not re.fullmatch(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+", args.repository):
        parser.error("--repository must be owner/repository")
    try:
        publish(args)
    except (OSError, ValueError, RuntimeError, subprocess.CalledProcessError) as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
